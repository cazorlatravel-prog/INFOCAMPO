-- -----------------------------------------------------------
-- Trigger reutilizable para updated_at
-- -----------------------------------------------------------
CREATE OR REPLACE FUNCTION trigger_set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- -----------------------------------------------------------
-- 1. EMPRESAS
-- -----------------------------------------------------------
CREATE TABLE IF NOT EXISTS empresas (
    id                      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                  VARCHAR(200) NOT NULL,
    formato_nombre_foto     SMALLINT NOT NULL DEFAULT 1,
    op_mostrar_empresa      SMALLINT NOT NULL DEFAULT 0,
    op_mostrar_infraestructura SMALLINT NOT NULL DEFAULT 0,
    op_mostrar_situacion    SMALLINT NOT NULL DEFAULT 0,
    op_mostrar_mapa         SMALLINT NOT NULL DEFAULT 0,
    op_mapa_zoom            SMALLINT NOT NULL DEFAULT 9,
    op_mostrar_capas_infra  SMALLINT NOT NULL DEFAULT 0,
    plan_suscripcion        VARCHAR(20) NOT NULL DEFAULT 'free'
                            CHECK (plan_suscripcion IN ('free','basic','professional','enterprise')),
    nif                     VARCHAR(20) DEFAULT NULL,
    email_contacto          VARCHAR(255) DEFAULT NULL,
    activa                  SMALLINT NOT NULL DEFAULT 1,
    licencia_inicio         DATE DEFAULT NULL,
    licencia_fin            DATE DEFAULT NULL,
    max_usuarios            INT NOT NULL DEFAULT 10,
    max_infraestructuras    INT NOT NULL DEFAULT 50,
    logo_url                VARCHAR(512) DEFAULT NULL,
    wm_mostrar_fecha        SMALLINT NOT NULL DEFAULT 1,
    wm_mostrar_coordenadas  SMALLINT NOT NULL DEFAULT 1,
    wm_mostrar_orientacion  SMALLINT NOT NULL DEFAULT 1,
    wm_mostrar_ubicacion    SMALLINT NOT NULL DEFAULT 1,
    wm_mostrar_pais         SMALLINT NOT NULL DEFAULT 1,
    wm_mostrar_brujula      SMALLINT NOT NULL DEFAULT 1,
    wm_mostrar_codigo_infra SMALLINT NOT NULL DEFAULT 0,
    wm_mostrar_situacion    SMALLINT NOT NULL DEFAULT 0,
    wm_mostrar_tipo_foto    SMALLINT NOT NULL DEFAULT 0,
    wm_mostrar_mapa         SMALLINT NOT NULL DEFAULT 0,
    wm_mapa_zoom            SMALLINT NOT NULL DEFAULT 15,
    wm_mapa_tamano          SMALLINT NOT NULL DEFAULT 2,
    wm_texto_tamano         SMALLINT NOT NULL DEFAULT 2,
    created_at              TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at              TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_empresas_plan ON empresas (plan_suscripcion);
CREATE INDEX IF NOT EXISTS idx_empresas_activa ON empresas (activa);

CREATE TRIGGER trg_empresas_updated_at
    BEFORE UPDATE ON empresas
    FOR EACH ROW EXECUTE FUNCTION trigger_set_updated_at();

-- -----------------------------------------------------------
-- 2. USUARIOS
-- -----------------------------------------------------------
CREATE TABLE IF NOT EXISTS usuarios (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id      INT NOT NULL REFERENCES empresas (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    nombre          VARCHAR(150) NOT NULL,
    email           VARCHAR(255) DEFAULT NULL,
    telefono        VARCHAR(20) DEFAULT NULL,
    password        VARCHAR(255) NOT NULL,
    rol             VARCHAR(20) NOT NULL DEFAULT 'operador'
                    CHECK (rol IN ('superadmin','admin','supervisor','operador')),
    activo          SMALLINT NOT NULL DEFAULT 1,
    ultimo_login    TIMESTAMP DEFAULT NULL,
    created_at      TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_usuarios_email ON usuarios (email) WHERE email IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_usuarios_telefono ON usuarios (telefono) WHERE telefono IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_usuarios_empresa ON usuarios (empresa_id);
CREATE INDEX IF NOT EXISTS idx_usuarios_rol ON usuarios (rol);
CREATE INDEX IF NOT EXISTS idx_usuarios_empresa_rol ON usuarios (empresa_id, rol, activo);

CREATE TRIGGER trg_usuarios_updated_at
    BEFORE UPDATE ON usuarios
    FOR EACH ROW EXECUTE FUNCTION trigger_set_updated_at();

