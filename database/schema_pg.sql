-- -----------------------------------------------------------
-- 6. REGISTROS (inspecciones / fotos de campo)
-- -----------------------------------------------------------
CREATE TABLE IF NOT EXISTS registros (
    id                      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    infra_id                INT NOT NULL REFERENCES infraestructuras (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    unidad_obra_id          INT DEFAULT NULL,
    tipo_trabajo_id         INT DEFAULT NULL,
    usuario_id              INT NOT NULL REFERENCES usuarios (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    fecha                   TIMESTAMP NOT NULL DEFAULT NOW(),
    lat_real                DECIMAL(10,7) DEFAULT 0,
    lon_real                DECIMAL(10,7) DEFAULT 0,
    url_cloudinary          VARCHAR(512) DEFAULT NULL,
    datos_tecnicos          JSONB DEFAULT NULL,
    estado_incidencia       VARCHAR(20) NOT NULL DEFAULT 'antes'
                            CHECK (estado_incidencia IN ('antes','durante','despues')),
    observaciones           TEXT DEFAULT NULL,
    tipo_foto               VARCHAR(20) NOT NULL DEFAULT 'aleatorio'
                            CHECK (tipo_foto IN ('aleatorio','comparativo')),
    secuencia_comparativa   INT DEFAULT NULL,
    nombre_archivo          VARCHAR(255) DEFAULT NULL,
    client_token            VARCHAR(64) DEFAULT NULL,
    es_visita_sin_foto      SMALLINT NOT NULL DEFAULT 0,
    created_at              TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_reg_infra ON registros (infra_id);
CREATE INDEX IF NOT EXISTS idx_reg_usuario ON registros (usuario_id);
CREATE INDEX IF NOT EXISTS idx_reg_fecha ON registros (fecha);
CREATE INDEX IF NOT EXISTS idx_reg_estado ON registros (estado_incidencia);
CREATE INDEX IF NOT EXISTS idx_reg_tipo_foto ON registros (tipo_foto);
CREATE INDEX IF NOT EXISTS idx_reg_unidad_obra ON registros (unidad_obra_id);
CREATE INDEX IF NOT EXISTS idx_reg_tipo_trabajo ON registros (tipo_trabajo_id);
CREATE INDEX IF NOT EXISTS idx_registros_infra_fecha ON registros (infra_id, fecha DESC);
CREATE INDEX IF NOT EXISTS idx_registros_infra_estado ON registros (infra_id, estado_incidencia);
CREATE INDEX IF NOT EXISTS idx_registros_usuario_fecha ON registros (usuario_id, fecha DESC);
CREATE UNIQUE INDEX IF NOT EXISTS uq_registros_client_token ON registros (client_token) WHERE client_token IS NOT NULL;

